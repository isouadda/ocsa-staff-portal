// ============================================================
// THE PORTAL'S OWN WORDS
//
// Every word the portal draws itself lives here in English,
// Spanish and French. Help's answers and the two report forms
// are not in this file: those arrive from the API already in
// the chosen language.
//
// The key is the exact English a screen shows today. A reviewer
// reads each key's Spanish and French side by side in
// translation/portal_words.csv, and a key with no entry falls
// back to the English, so a word added later shows in English
// rather than blank or as a code.
//
// Accented letters, opening marks and French's no-break spaces
// are written as \u escapes, so this file stays ASCII while the
// screen shows correct Spanish and French. The review sheet is
// the file written in real characters, because people read
// that one.
// ============================================================

// The language every screen reads. The root component sets it
// from the one piece of state Step 70 already keeps, during its
// own render, so the choice is in place before any screen below
// renders and choosing Spanish in Settings changes the whole
// portal at once with no reload. A module value rather than a
// context, because a good half of the portal's words are drawn
// by plain helper functions that cannot hold a hook.
let current = "en";

// Every language this file holds words for, each named in its own
// language, in the order the pickers draw them. A language added
// later is one more line here and its table below.
export const LANGUAGE_NAMES = { en: "English", es: "Espa\u00f1ol", fr: "Fran\u00e7ais" };

// The languages the portal offers. English and Spanish always; French
// only once the API lists it (Step 209), so until then no screen shows
// it and no call names it. The list the API last gave is kept on this
// phone, so the first frame and the small script at the top of
// public/index.html know what is offered before the API is asked.
export const LANGUAGES_KEY = "ocsa-staff-languages";
const ALWAYS = ["en", "es"];

// A list is kept when it names English and Spanish, and is cut to the
// languages this file holds words for, in the order it gives them.
// Anything else is null.
export function offeredFrom(list) {
  if (!Array.isArray(list) || list.indexOf("en") === -1 || list.indexOf("es") === -1) return null;
  const out = [];
  list.forEach((code) => {
    if (typeof code === "string" && Object.prototype.hasOwnProperty.call(LANGUAGE_NAMES, code) && out.indexOf(code) === -1) out.push(code);
  });
  return out;
}

function storedOffered() {
  try { return offeredFrom(JSON.parse(window.localStorage.getItem(LANGUAGES_KEY))) || ALWAYS; } catch (e) { return ALWAYS; }
}

let offered = storedOffered();

export function offeredLanguages() {
  return offered;
}

// What the API said it speaks. A list naming English and Spanish is
// offered from here and kept on this phone. null, the API saying it has
// no list, puts back English and Spanish and forgets a list kept from an
// earlier answer, so the next start does not offer what the API no
// longer lists. The language on the screen falls to English here when
// it is no longer offered; the portal then moves it to the phone's.
export function setOfferedLanguages(list) {
  const next = offeredFrom(list);
  offered = next || ALWAYS;
  try {
    if (next) window.localStorage.setItem(LANGUAGES_KEY, JSON.stringify(next));
    else if (window.localStorage.getItem(LANGUAGES_KEY) !== null) window.localStorage.removeItem(LANGUAGES_KEY);
  } catch (e) {}
  if (!isOffered(current)) current = "en";
}

export function isOffered(lang) {
  return offered.indexOf(lang) !== -1;
}

// A language that is not offered falls to English, the way anything
// but Spanish always has.
export function setWordsLanguage(lang) {
  current = isOffered(lang) ? lang : "en";
}

export function wordsLanguage() {
  return current;
}

// The language a call names: the one given, or with none the one on
// the screen, when it is offered, and English otherwise. Every path
// that sends a language asks here, so none can send one the API has
// not listed.
export function languageToSend(lang) {
  const v = lang === undefined ? current : lang;
  return isOffered(v) ? v : "en";
}

